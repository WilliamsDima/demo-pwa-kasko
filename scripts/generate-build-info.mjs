import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

function readCommit() {
  try {
    const dirty = execSync('git status --porcelain').toString().trim().length > 0;
    const sha = execSync('git rev-parse --short HEAD').toString().trim();
    return dirty ? `${sha}+` : sha;
  } catch {
    return 'dev';
  }
}

const commit = readCommit();
const builtAt = new Date().toISOString();

const content = `// Auto-generated by scripts/generate-build-info.mjs before every build/serve — do not edit by hand.
export const BUILD_INFO = {
  commit: '${commit}',
  builtAt: '${builtAt}',
} as const;
`;

writeFileSync(new URL('../src/app/core/build-info.ts', import.meta.url), content);
console.log(`build-info.ts written: ${commit} @ ${builtAt}`);
